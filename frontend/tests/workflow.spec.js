import { test, expect } from '@playwright/test'

test('real upload → diagnosis → approval → training → prediction and export', async ({ page }) => {
 const errors=[]; page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Your research starts with a dataset'})).toBeVisible()
 await page.screenshot({path:'../docs/dashboard-empty.png',fullPage:true})
 await page.getByRole('link',{name:'Datasets',exact:true}).click()
 // Deliberately synthetic fixture, not a user dataset or a claimed research result.
 const lines=['value,segment,target']
 for(let i=0;i<120;i++)lines.push(`${i%11===0?'':i},${i%2?'north':' south '},${i>59?'positive':'negative'}`)
 await page.getByLabel('Dataset file').setInputFiles({name:'synthetic-browser-fixture.csv',mimeType:'text/csv',buffer:Buffer.from(lines.join('\n'))})
 await page.getByRole('button',{name:'Upload & analyze',exact:true}).click()
 await expect(page.getByRole('heading',{name:'synthetic-browser-fixture.csv'})).toBeVisible()
 await page.getByRole('button',{name:'Target & features'}).click()
 await page.getByLabel('Prediction target').selectOption('target')
 await page.getByRole('button',{name:'Save selection & analyze'}).click()
 await expect(page.getByText('Selection saved')).toBeVisible()
 await page.getByRole('link',{name:'Quality inspector',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Missing observations',exact:true})).toBeVisible({timeout:15000})
 await page.getByRole('link',{name:'Repair studio',exact:true}).click()
 await page.getByLabel('Approve Impute · value', {exact:true}).check()
 await page.getByRole('button',{name:'Preview approved repairs'}).click()
 await expect(page.getByRole('heading',{name:'Review before applying'})).toBeVisible()
 await page.getByRole('button',{name:'Apply these approved repairs'}).click()
 await expect(page.getByText('Approved repairs saved as a new version. Original data is unchanged.')).toBeVisible()
 await page.getByRole('link',{name:'Train & evaluate',exact:true}).click()
 await page.getByRole('combobox',{name:'Algorithm',exact:true}).selectOption('tree')
 await page.getByRole('button',{name:'Validate experiment configuration'}).click()
 await expect(page.getByRole('heading',{name:'Review the exact experiment'})).toBeVisible()
 await page.getByRole('button',{name:'Start real three-arm training'}).click()
 await expect(page.getByRole('link',{name:'View measured results'})).toBeVisible({timeout:45000})
 await page.getByRole('link',{name:'View measured results'}).click()
 await expect(page.getByRole('heading',{name:'All evaluation metrics'})).toBeVisible()
 await expect(page.locator('td').filter({hasText:'standard'}).first()).toBeVisible()
 await page.getByRole('link',{name:'Predictions',exact:true}).click()
 await page.getByLabel('value', {exact:false}).fill('88')
 await page.getByLabel('segment', {exact:false}).fill('north')
 await page.getByRole('button',{name:'Make prediction',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Prediction result',exact:true})).toBeVisible()
 await page.getByRole('link',{name:'History & reports',exact:true}).click()
 const download=page.waitForEvent('download');await page.getByRole('link',{name:'JSON',exact:true}).click();expect((await download).suggestedFilename()).toBe('experiment-report.json')
 expect(errors).toEqual([])
})

